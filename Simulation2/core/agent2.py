"""
core/agent2.py - Task 2 Single-Shot Agent with Cross-Agent Memory Inheritance.

Proves Pillar 4: Cross-Agent Memory prevents repeating mistakes.
Agent 2 receives read-only access to Task 1's entire memory ledger
(all policies, failure traces, critiques, and evolved prompts).
In a SINGLE attempt (no iterative loop, no retries, exactly 1 LLM call),
Agent 2 synthesizes an optimal policy that achieves >= 85% success rate
and >= 5/6 treasure acquisition, while citing past failure traces to justify
its derived parameter costs.
"""

