    def _generate_with_llm(self, prompt: str, api_key: str) -> List[TestCase]:
        """Uses Featherless LLM to dynamically generate test scripts."""
        import requests

        sys_prompt = (
            "You are TestCaseCreator, an expert automated test suite generator.\n"
            "Analyze the given specification and return a JSON array containing 6 to 8 test cases.\n"
            "Each test case must have fields: 'id' (str), 'category' (str: functional|boundary|safety|stress), "
            "'description' (str), 'script' (valid standalone Python code testing 'solution.py' and exiting with sys.exit(0) on success).\n"
            "Return STRICT JSON only, enclosed in ```json ... ```."
        )

        resp = requests.post(
            "https://api.featherless.ai/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            json={
                "model": self.model,
                "messages": [
                    {"role": "system", "content": sys_prompt},
                    {"role": "user", "content": f"Specification:\n{prompt}"},
                ],
                "temperature": 0.0,
            },
            timeout=15,
        )
        if resp.status_code == 200:
            data = resp.json()
            raw_text = data["choices"][0]["message"]["content"]
            match = re.search(r"```(?:json)?\s*(\[[\s\S]*?\])\s*```", raw_text)
            if match:
                parsed = json.loads(match.group(1))
                test_cases = []
                for item in parsed:
                    # Validate python syntax of generated script
                    ast.parse(item["script"])
                    test_cases.append(TestCase(
                        id=item["id"],
                        category=item.get("category", "functional"),
                        description=item.get("description", ""),
                        script=item["script"],
                    ))
                return test_cases

        return []
